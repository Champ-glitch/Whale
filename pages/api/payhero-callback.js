import { sendTelegramMessage, sendTelegramAnimation } from "../../lib/telegram.js";
import { kesToUsdt } from "../../lib/rates.js";
import { getRandomQuote, getRandomGif } from "../../lib/extras.js";
import { parseReference } from "../../lib/reference.js";
import { sendSMS } from "../../lib/sms.js";
import {
  updateInvoiceStatus,
  recordSuccessStats,
  addPendingSplit,
  getPendingSplitTotal,
  getAutoApprove,
  approvePendingSplit,
  getSavingsBalance,
  getBalance,
} from "../../lib/kv.js";

const SPLIT_RATIO = 0.4; // 40% of every deposit is earmarked for savings

// Fires on ANY successful C2B deposit to main_collection - payment links,
// self-STK, or a manual Till deposit with no reference at all. This is the
// ONLY place the split is triggered from - never from a bot command - so
// money is always caught regardless of how it arrived. No minimum amount.
async function triggerSplit(chatId, amount, meta = {}) {
  const amt = Number(amount);
  if (!amt || amt <= 0) return;

  const savingsShare = Math.round(amt * SPLIT_RATIO * 100) / 100;
  const mainShare = Math.round((amt - savingsShare) * 100) / 100;
  const pendingTotal = await addPendingSplit(savingsShare, meta);

  const autoApprove = await getAutoApprove();
  if (autoApprove) {
    const moved = await approvePendingSplit();
    const savings = await getSavingsBalance();
    const main = await getBalance();
    await sendTelegramMessage(
      chatId,
      `🔀 *Auto-Split (auto-approved)*\n` +
        `KES ${amt.toLocaleString()} received\n` +
        `💰 60% stays in Main: KES ${mainShare.toLocaleString()}\n` +
        `🏦 40% → Savings: KES ${savingsShare.toLocaleString()} (moved automatically)\n\n` +
        `💰 Main: KES ${main.toLocaleString()}   🏦 Savings: KES ${savings.toLocaleString()}`
    );
    return;
  }

  await sendTelegramMessage(
    chatId,
    `🔀 *Auto-Split*\n` +
      `KES ${amt.toLocaleString()} received\n` +
      `💰 60% stays in Main: KES ${mainShare.toLocaleString()}\n` +
      `🏦 40% → Savings: KES ${savingsShare.toLocaleString()}\n\n` +
      `⏳ Pending savings transfer: *KES ${pendingTotal.toLocaleString()}*\n` +
      `Reply *WHALE approve* to move it, or /autoapprove on to skip this step.`
  );
}

export default async function handler(req, res) {
  if (req.method !== "POST") {
    return res.status(200).send("OK");
  }

  try {
    const body = req.body;
    console.log("PayHero callback:", JSON.stringify(body));

    const response = body?.response || {};
    const rawReference =
      response.ExternalReference || body?.external_reference || body?.reference;

    const success = response.ResultCode === 0 || response.Status === "Success";
    const amount = response.Amount;
    const senderPhone = response.Phone;
    const mpesaReceipt = response.MpesaReceiptNumber;

    const parsed = parseReference(rawReference);

    // ---- Manual C2B deposit direct to Till/Business number ----
    // No WHALE:: reference means it wasn't generated by /pay or /link.
    // Still catch it: record it, split it, and notify the owner directly
    // since there's no chatId to route the notification through.
    if (!parsed) {
      console.warn("Manual/direct C2B deposit (no WHALE:: reference):", rawReference);
      if (!success) {
        return res.status(200).json({ ok: true });
      }
      const owner = process.env.OWNER_CHAT_ID;
      if (!owner) {
        console.warn("No OWNER_CHAT_ID set - can't notify about manual deposit.");
        return res.status(200).json({ ok: true });
      }

      const stats = await recordSuccessStats(Number(amount) || 0);

      await sendTelegramMessage(
        owner,
        `📥 *Direct deposit detected*\n` +
          `KES ${amount ?? "?"}\n` +
          (senderPhone ? `From: ${senderPhone}\n` : "") +
          (mpesaReceipt ? `M-Pesa Receipt: ${mpesaReceipt}\n` : "") +
          `Reference: \`${rawReference || "none"}\``
      );

      await triggerSplit(owner, amount, {
        source: "manual_till",
        mpesaReceipt: mpesaReceipt || null,
        senderPhone: senderPhone || null,
      });

      if (stats.crossedMilestone) {
        await sendTelegramMessage(
          owner,
          `🎉🎉 *MILESTONE!* You've now collected over *KES ${stats.crossedMilestone.toLocaleString()}* all-time with WHALE_SYS Pay!`
        );
      }

      return res.status(200).json({ ok: true });
    }

    // ---- Payment links (/link) and self-prompted STK (/pay) ----
    const { chatId, invoiceCode } = parsed;

    if (invoiceCode) {
      await updateInvoiceStatus(invoiceCode, success ? "success" : "failed");
    }

    if (success) {
      let usdtLine = "";
      if (amount) {
        const usdt = await kesToUsdt(amount);
        if (usdt) usdtLine = `\n💵 ≈ ${usdt} USDT`;
      }

      const quote = getRandomQuote();
      const caption =
        `✅ *Payment received!*\n` +
        `KES ${amount ?? "?"}${usdtLine}\n` +
        (senderPhone ? `From: ${senderPhone}\n` : "") +
        (mpesaReceipt ? `M-Pesa Receipt: ${mpesaReceipt}\n` : "") +
        `Reference: \`${rawReference}\`\n\n` +
        `_${quote}_`;

      await sendTelegramAnimation(chatId, getRandomGif(), caption);

      const stats = await recordSuccessStats(Number(amount) || 0);

      await triggerSplit(chatId, amount, {
        source: invoiceCode ? "payment_link" : "self_stk",
        invoiceCode: invoiceCode || null,
        mpesaReceipt: mpesaReceipt || null,
      });

      if (senderPhone) {
        await sendSMS(
          senderPhone,
          `Thank you for your payment of KES ${amount} to Whale Enterprise. M-Pesa Ref: ${mpesaReceipt || rawReference}. We appreciate your business!`
        );
      }

      if (stats.crossedMilestone) {
        await sendTelegramMessage(
          chatId,
          `🎉🎉 *MILESTONE!* You've now collected over *KES ${stats.crossedMilestone.toLocaleString()}* all-time with WHALE_SYS Pay!`
        );
      }
    } else {
      await sendTelegramMessage(
        chatId,
        `❌ Payment not completed (cancelled or failed). Reference: \`${rawReference}\``
      );
    }

    return res.status(200).json({ ok: true });
  } catch (err) {
    console.error("payhero-callback error:", err);
    const owner = process.env.OWNER_CHAT_ID;
    if (owner) {
      try {
        await sendTelegramMessage(owner, `🚨 *System error in payment callback*\n\`${err.message}\`\n\nCheck Vercel logs for details.`);
      } catch (e) {
        console.error("Failed to send error alert:", e);
      }
    }
    return res.status(200).json({ ok: true });
  }
}
